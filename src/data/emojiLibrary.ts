const RECENT_KEY = 'tg_recent_emojis_v1';

export function getRecentEmojis(): string[] {
  try {
    const stored = localStorage.getItem(RECENT_KEY);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed.slice(0, 16);
      }
    }
  } catch {}
  return INSTANT_QUICK_EMOJIS.slice(0, 8);
}

export function saveRecentEmoji(emoji: string): void {
  try {
    const current = getRecentEmojis();
    const updated = [emoji, ...current.filter((e) => e !== emoji)].slice(0, 24);
    localStorage.setItem(RECENT_KEY, JSON.stringify(updated));
  } catch {}
}
